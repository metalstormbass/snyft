func (r *Reporter) printHTMLExecutiveSummary(w io.Writer) error {
	overall := calculateOverallRisk(r.stats)
	duration := r.stats.EndTime.Sub(r.stats.StartTime)

	overallCls := "low"
	switch overall {
	case "HIGH":
		overallCls = "high"
	case "MEDIUM":
		overallCls = "medium"
	}

	f(w, "<div class=\"dashboard\">\n")

	// Overall risk card
	riskCardClass := "risk-high"
	switch overall {
	case "MEDIUM":
		riskCardClass = "risk-med"
	case "LOW":
		riskCardClass = "risk-low"
	}
	f(w, "<div class=\"stat-card %s\">\n", riskCardClass)
	f(w, "<div class=\"stat-label\">Overall Risk</div>\n")
	f(w, "<div class=\"stat-value %s\">%s</div>\n", overallCls, overall)
	f(w, "</div>\n")

	// Packages card
	f(w, "<div class=\"stat-card risk-info\">\n")
	f(w, "<div class=\"stat-label\">Packages Analyzed</div>\n")
	f(w, "<div class=\"stat-value\">%d</div>\n", r.stats.TotalPackages)
	if r.stats.TotalPackages > 0 {
		f(w, "<div class=\"stat-breakdown\"><span class=\"high\">%d high</span><span class=\"med\">%d med</span><span class=\"low\">%d low</span></div>\n",
			r.stats.HighRisk, r.stats.MediumRisk, r.stats.LowRisk)
		// Risk meter bar
		total := float64(r.stats.TotalPackages)
		if total > 0 {
			f(w, "<div class=\"risk-meter\">")
			if r.stats.HighRisk > 0 {
				f(w, "<span class=\"seg-high\" style=\"width:%.1f%%\"></span>", float64(r.stats.HighRisk)/total*100)
			}
			if r.stats.MediumRisk > 0 {
				f(w, "<span class=\"seg-med\" style=\"width:%.1f%%\"></span>", float64(r.stats.MediumRisk)/total*100)
			}
			if r.stats.LowRisk > 0 {
				f(w, "<span class=\"seg-low\" style=\"width:%.1f%%\"></span>", float64(r.stats.LowRisk)/total*100)
			}
			f(w, "</div>\n")
		}
		// Package name lists by risk level with anchor links
		r.printHTMLPackageLinks(w)
	}
	f(w, "</div>\n")

	// Dependencies card
	if r.stats.DirectDeps > 0 || r.stats.TransitiveDeps > 0 {
		f(w, "<div class=\"stat-card risk-info\">\n")
		f(w, "<div class=\"stat-label\">Dependencies</div>\n")
		f(w, "<div class=\"stat-value\">%d</div>\n", r.stats.DirectDeps+r.stats.TransitiveDeps)
		f(w, "<div class=\"stat-sub\">%d direct &middot; %d transitive</div>\n", r.stats.DirectDeps, r.stats.TransitiveDeps)
		f(w, "</div>\n")
	}

	// Duration card
	f(w, "<div class=\"stat-card risk-info\">\n")
	f(w, "<div class=\"stat-label\">Scan Duration</div>\n")
	f(w, "<div class=\"stat-value\" style=\"font-size:22px\">%s</div>\n", html.EscapeString(formatDuration(duration)))
	f(w, "</div>\n")

	f(w, "</div>\n")
	return nil
}

// printHTMLPackageLinks renders package names grouped by risk level as
// clickable anchor links that jump to the corresponding package detail section.
func (r *Reporter) printHTMLPackageLinks(w io.Writer) {
	var high, medium, low []models.AnalysisResult
	for _, result := range r.results {
		switch result.RiskLevel {
		case "HIGH":
			high = append(high, result)
		case "MEDIUM":
			medium = append(medium, result)
		case "LOW":
			low = append(low, result)
		}
	}

	f(w, "<div class=\"pkg-links\">\n")
	if len(high) > 0 {
		f(w, "<div class=\"pkg-links-group\"><span class=\"group-label high\">High:</span>")
		for i, result := range high {
			if i > 0 {
				f(w, ",")
			}
			slug := packageSlug(result.Dependency.Name)
			f(w, " <a href=\"#pkg-%s\">%s</a>", slug, html.EscapeString(result.Dependency.Name))
		}
		f(w, "</div>\n")
	}
	if len(medium) > 0 {
		f(w, "<div class=\"pkg-links-group\"><span class=\"group-label med\">Medium:</span>")
		for i, result := range medium {
			if i > 0 {
				f(w, ",")
			}
			slug := packageSlug(result.Dependency.Name)
			f(w, " <a href=\"#pkg-%s\">%s</a>", slug, html.EscapeString(result.Dependency.Name))
		}
		f(w, "</div>\n")
	}
	if len(low) > 0 {
		f(w, "<div class=\"pkg-links-group\"><span class=\"group-label low\">Low:</span>")
		for i, result := range low {
			if i > 0 {
				f(w, ",")
			}
			slug := packageSlug(result.Dependency.Name)
			f(w, " <a href=\"#pkg-%s\">%s</a>", slug, html.EscapeString(result.Dependency.Name))
		}
		f(w, "</div>\n")
	}
	f(w, "</div>\n")
}

func (r *Reporter) printHTMLTopFindings(w io.Writer) {
	criticalIssues := r.extractCriticalIssues(5)
	if len(criticalIssues) == 0 {
		return
	}

	f(w, "<section class=\"section\">\n")
	f(w, "<h2 class=\"section-title\">Top Priority Findings</h2>\n")
	f(w, "<p class=\"section-desc\">Most critical supply chain risk signals across all packages.</p>\n")

	for i, issue := range criticalIssues {
		sevCls := "medium"
		if issue.Severity == "HIGH" || issue.Severity == "CRITICAL" {
			sevCls = "high"
		}
		f(w, "<div class=\"top-finding\">\n")
		f(w, "<div class=\"top-finding-num\">%d</div>\n", i+1)
		f(w, "<div class=\"top-finding-body\">\n")
		f(w, "<div><span class=\"top-finding-pkg\">%s@%s</span><span class=\"top-finding-eco\">%s</span> <span class=\"sev-badge %s\">%s</span></div>\n",
			html.EscapeString(issue.PackageName),
			html.EscapeString(issue.PackageVersion),
			html.EscapeString(issue.Ecosystem),
			sevCls,
			html.EscapeString(issue.Severity))
		f(w, "<div class=\"top-finding-desc\">%s</div>\n", html.EscapeString(issue.Description))
		f(w, "</div>\n")
		f(w, "</div>\n")
	}

	f(w, "</section>\n")
}

func (r *Reporter) printHTMLRiskAreas(w io.Writer) {
	areas := r.generateRiskAreas()

	f(w, "<section class=\"section\">\n")
	f(w, "<h2 class=\"section-title\">Key Risk Areas</h2>\n")
	f(w, "<p class=\"section-desc\">Cross-cutting supply chain risk patterns across all analyzed packages.</p>\n")

	if len(areas) == 0 {
		f(w, "<div class=\"success-msg\">&#10003; No critical supply chain risk factors identified.</div>\n")
	} else {
		for _, area := range areas {
			var areaCls string
			switch area.Tag {
			case "HIGH RISK":
				areaCls = "area-high"
			default:
				areaCls = "area-med"
			}
			f(w, "<div class=\"risk-area %s\">\n", areaCls)
			f(w, "<div class=\"risk-area-tag\">%s</div>\n", html.EscapeString(area.Tag))
			f(w, "<div class=\"risk-area-summary\">%s</div>\n", html.EscapeString(area.Summary))
			f(w, "<div class=\"risk-area-explain\">%s</div>\n", html.EscapeString(area.Explanation))
			if len(area.Examples) > 0 {
				f(w, "<div class=\"risk-area-examples\">Affected: ")
				for i, name := range area.Examples {
					if i > 0 {
						f(w, ", ")
					}
					slug := packageSlug(name)
					f(w, "<a href=\"#pkg-%s\">%s</a>", slug, html.EscapeString(name))
				}
				f(w, "</div>\n")
			}
			f(w, "</div>\n")
		}
	}

	f(w, "</section>\n")
}

func (r *Reporter) printHTMLPackage(w io.Writer, result models.AnalysisResult, index int) {
	cls := "low"
	switch result.RiskLevel {
	case "HIGH":
		cls = "high"
	case "MEDIUM":
		cls = "medium"
	}

	// First 3 HIGH risk packages start expanded
	openCls := ""
	if result.RiskLevel == "HIGH" && index < 3 {
		openCls = " open"
	}

	slug := packageSlug(result.Dependency.Name)
	f(w, "<div class=\"pkg-card %s%s\" id=\"pkg-%s\">\n", cls, openCls, slug)

	// Clickable header
	f(w, "<div class=\"pkg-header\" onclick=\"toggle('%s')\">\n", slug)
	f(w, "<div class=\"pkg-left\">\n")
	name := html.EscapeString(result.Dependency.Name) + "@" + html.EscapeString(result.Dependency.Version)
	f(w, "<span class=\"pkg-name\">%s</span>\n", name)
	if result.Dependency.IsTransitive {
		f(w, "<span class=\"pkg-trans\">transitive</span>\n")
	}
	f(w, "</div>\n")
	f(w, "<div class=\"pkg-right\">\n")
	if result.SupplyChainScore != nil {
		ms := maxScore(result.SupplyChainScore)
		f(w, "<span class=\"pkg-score\">%d/%d</span>\n", result.SupplyChainScore.TotalScore, ms)
	}
	f(w, "<span class=\"risk-badge %s\">%s</span>\n", cls, result.RiskLevel)
	f(w, "<svg class=\"chevron\" viewBox=\"0 0 20 20\" fill=\"currentColor\"><path fill-rule=\"evenodd\" d=\"M5.23 7.21a.75.75 0 011.06.02L10 11.168l3.71-3.938a.75.75 0 111.08 1.04l-4.25 4.5a.75.75 0 01-1.08 0l-4.25-4.5a.75.75 0 01.02-1.06z\" clip-rule=\"evenodd\"/></svg>\n")
	f(w, "</div>\n")
	f(w, "</div>\n")

	// Expandable body
	f(w, "<div class=\"pkg-body\">\n")

	// Metadata
	f(w, "<div class=\"pkg-meta\">\n")
	f(w, "<span><span class=\"meta-label\">Ecosystem:</span> %s</span>\n", html.EscapeString(string(result.Dependency.Ecosystem)))
	if result.RepositoryURL != "" {
		f(w, "<span><span class=\"meta-label\">Repo:</span> <a href=\"%s\" target=\"_blank\" rel=\"noopener\">%s</a></span>\n",
			html.EscapeString(result.RepositoryURL), html.EscapeString(result.RepositoryURL))
	}
	if result.SourceCodeAvailable {
		f(w, "<span><span class=\"meta-label\">Source:</span> Available</span>\n")
	} else {
		f(w, "<span><span class=\"meta-label\">Source:</span> Unavailable</span>\n")
	}
	f(w, "</div>\n")

	// Category scores (verbose mode or always if supply chain score exists)
	if result.SupplyChainScore != nil {
		f(w, "<div class=\"cat-grid\">\n")
		for _, cat := range categoryList(result.SupplyChainScore.CategoryScores) {
			if cat.Score.Skipped {
				f(w, "<div class=\"cat-item skipped\"><span class=\"cat-dot dot-skip\"></span><span class=\"cat-name\">%s</span><span class=\"cat-score\">SKIP</span></div>\n",
					html.EscapeString(cat.Name))
				continue
			}
			riskCls := fmt.Sprintf("risk-%d", cat.Score.RiskPoints)
			dotCls := fmt.Sprintf("dot-%d", cat.Score.RiskPoints)
			verified := ""
			if !cat.Score.Verified {
				verified = " <span class=\"cat-verified\">?</span>"
			}
			f(w, "<div class=\"cat-item %s\"><span class=\"cat-dot %s\"></span><span class=\"cat-name\">%s</span><span class=\"cat-score\">%d/2%s</span></div>\n",
				riskCls, dotCls, html.EscapeString(cat.Name), cat.Score.Score, verified)
		}
		f(w, "</div>\n")
	}

	// Findings
	if len(result.Findings) > 0 {
		f(w, "<div class=\"findings-title\">Risk Findings</div>\n")
		for _, finding := range result.Findings {
			fc := "f-" + severityToClass(finding.Severity)
			f(w, "<div class=\"finding-item %s\">\n", fc)
			f(w, "<span class=\"sev-badge %s\">%s</span>\n",
				severityToClass(finding.Severity), html.EscapeString(finding.Severity))
			f(w, "<div class=\"finding-desc\">%s</div>\n", html.EscapeString(finding.Description))
			if finding.SourceURL != "" {
				f(w, "<div class=\"finding-extra\">Source: <a href=\"%s\" target=\"_blank\" rel=\"noopener\">%s</a></div>\n",
					html.EscapeString(finding.SourceURL), html.EscapeString(finding.SourceURL))
			}
			if finding.Evidence != "" && r.config.Verbose {
				f(w, "<div class=\"finding-extra\">Evidence: %s</div>\n", html.EscapeString(finding.Evidence))
			}
			if finding.Methodology != "" && r.config.Verbose {
				f(w, "<div class=\"finding-extra\">Method: %s</div>\n", html.EscapeString(finding.Methodology))
			}
			f(w, "</div>\n")
		}
	}

	f(w, "</div>\n") // pkg-body
	f(w, "</div>\n") // pkg-card
}

func severityToClass(severity string) string {
	switch severity {
	case "CRITICAL":
		return "critical"
	case "HIGH":
		return "high"
	case "MEDIUM":
		return "medium"
	case "LOW":
		return "low"
	default:
		return "low"
	}
}

