func (r *Reporter) generateHTML() error {
	bw := bufio.NewWriterSize(r.config.Writer, 256*1024)
	w := io.Writer(bw)

	// Sort results by risk score descending, findings by severity descending
	sorted := r.sortedResults()

	if _, err := fmt.Fprint(w, `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Snyft Supply Chain Risk Report</title>
<style>
`); err != nil {
		return err
	}
	r.printHTMLStyles(w)
	if _, err := fmt.Fprint(w, `</style>
</head>
<body>
<div class="wrap">
`); err != nil {
		return err
	}

	r.printHTMLHeader(w)
	if err := r.printHTMLExecutiveSummary(w); err != nil {
		return err
	}
	r.printHTMLExecutiveNarrative(w)
	r.printHTMLRiskAreas(w)

	// Detailed findings
	f(w, "<section class=\"section\">\n")
	f(w, "<h2 class=\"section-title\">Package Details</h2>\n")
	f(w, "<p class=\"section-desc\">Click a package to expand its full analysis. Sorted by risk score, highest first.</p>\n")
	for i, result := range sorted {
		r.printHTMLPackage(w, result, i)
	}
	f(w, "</section>\n")

	// Footer
	f(w, "<footer class=\"footer\">Generated by <strong>Snyft</strong> &mdash; <em>Does it pass the snyft test?</em> &mdash; %s</footer>\n",
		time.Now().Format("2006-01-02 15:04:05"))

	f(w, "</div>\n")
	r.printHTMLScript(w)
	f(w, "</body>\n</html>\n")
	return bw.Flush()
}

func riskOrdinal(level string) int {
	switch level {
	case "HIGH":
		return 3
	case "MEDIUM":
		return 2
	case "LOW":
		return 1
	default:
		return 0
	}
}

// packageSlug generates an HTML-safe ID from a package name.
// Non-alphanumeric characters are replaced with hyphens and leading/trailing
// hyphens are removed.
func packageSlug(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(name) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteByte('-')
		}
	}
	return strings.Trim(b.String(), "-")
}

